// Embeds supabase/functions/ingest-product-page/fixtures/* into fixtures.generated.ts
// so the deployed function bundle always contains them. Run: deno run -A scripts/build-fixtures.ts
const dir = new URL("../supabase/functions/ingest-product-page/fixtures/", import.meta.url);
const files: Record<string, string> = {};
for await (const e of Deno.readDir(dir)) if (e.isFile) files[e.name] = await Deno.readTextFile(new URL(e.name, dir));
const sorted = Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b)));
const out = `// GENERATED by scripts/build-fixtures.ts from ./fixtures/*. Do not edit.\nexport const FIXTURE_FILES: Record<string, string> = ${
  JSON.stringify(sorted, null, 2)
};\n`;
await Deno.writeTextFile(new URL("../fixtures.generated.ts", dir), out);
console.log(`embedded ${Object.keys(sorted).length} fixture files`);
